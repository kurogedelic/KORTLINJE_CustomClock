inline void draw(IkeaMatrix::Frame &frame, const char *text) {
  frame.clear();
  for (int i = 0; i < 5 && text[i]; ++i) {
    const char *found = strchr(CHARS, text[i]);
    if (!found) continue;
    const uint8_t *glyph = GLYPHS[found - CHARS];
    for (int x = 0; x < 8; ++x)
      for (int y = 0; y < 7; ++y)
        if (glyph[x] & (1U << y)) frame.drawPixel(1 + i * 8 + x, 1 + y);
  }
}
